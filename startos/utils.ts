import { domainToASCII } from 'node:url'
import { sdk } from './sdk'

// Ports inside the shared network namespace. nginx serves TLS on 443 itself
// (the web binding is a passthrough), Prosody listens on 5222/5269, the portal
// and Prosody's HTTP API stay on loopback.
export const webPort = 443
export const c2sPort = 5222
export const s2sPort = 5269
export const portalPort = 5765

// One host carries all three bindings so a public domain added once reaches
// each of them (enabled per binding by the user).
export const hostId = 'main'
export const webInterfaceId = 'web'
export const c2sInterfaceId = 'c2s'
export const s2sInterfaceId = 's2s'

// The external Coturn package Snikket hands calls to. Mirrors jitsi-startos.
export const coturnId = 'coturn'
export const coturnVersionRange = '>=4.14.0:0'
export const coturnHostId = 'turn'
export const coturnTurnInterfaceId = 'turn'
export const coturnMountpoint = '/mnt/coturn'
export const coturnSecretPath = '/mnt/coturn/turn-secret'

export const snikketMountpoint = '/snikket'
// msmtp's config, generated by the package under the data volume and handed
// to Prosody's user by a chown oneshot. msmtp prefers this user config over
// the /etc/msmtprc upstream's entrypoint renders from SNIKKET_SMTP_URL.
export const msmtpSubpath = 'msmtp'
export const prosodyUser = 'prosody'
export const letsencryptSubpath = 'letsencrypt'
export const legoSubpath = 'lego'
export const legoMountpoint = '/.lego'

// Renew (or re-mint) when this many days or fewer remain.
export const renewBeforeDays = 30
// How often the certificate daemon looks for a renewal, and how soon it
// retries after a failed attempt.
export const renewalCheckIntervalMs = 12 * 60 * 60 * 1000
export const renewalRetryIntervalMs = 10 * 60 * 1000
// How often it checks whether the installed certificate changed under it
// (a pasted certificate, for instance) and needs the consumers reloaded.
export const certificateTickMs = 60 * 1000

export const domainPattern =
  '^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$'
export const emailPattern = '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$'
export const providerPattern = '^[a-z0-9]+$'

/** The punycode form Snikket keys its certificate directory by. */
export function domainAscii(domain: string): string {
  return domainToASCII(domain) || domain
}

/** Every hostname one Snikket instance serves, and its certificate must cover. */
export function snikketHostnames(domain: string): string[] {
  return [domain, `groups.${domain}`, `share.${domain}`]
}

// The data volume, mounted whole into both the server and the proxy: nginx
// reads the certificate tree that Prosody also imports.
export const snikketMounts = sdk.Mounts.of().mountVolume({
  volumeId: 'main',
  subpath: null,
  mountpoint: snikketMountpoint,
  readonly: false,
})

// lego keeps its ACME account and issued certificates under its own subpath.
export const legoMounts = sdk.Mounts.of().mountVolume({
  volumeId: 'main',
  subpath: legoSubpath,
  mountpoint: legoMountpoint,
  readonly: false,
})
